// newsbuild builds news-server with packs, the way xcaddy builds Caddy with plugins. A pack is a Go module whose
// package registers transports (fetch.RegisterTransport) and video resolvers (video.Register) from its init
// function; newsbuild writes a main package importing the core and every pack, and builds it.
//
//	newsbuild --with github.com/someone/news-sources-fr@v1.2.0 --with ../news-sources-xx/server -o news-server.exe
//
// Run it again to update: a pack named without a version, or with @latest, is fetched at its newest. A pack given
// as a folder (a path starting with ".", "/" or a drive letter, or any folder that exists) is built from that
// folder as it is, which is how to work on a pack, or use a private one, without publishing it.
package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"time"
)

const coreModule = "github.com/chencohensolutions/news-server-core-go"

// pseudo is the version a module replaced by a folder is required at; any version would do.
const pseudo = "v0.0.0-00010101000000-000000000000"

const usage = `usage: newsbuild [flags]

  --with <pack>     a pack to build in, repeatable: module[@version] (default @latest) or a folder
  --core <core>     the core: module[@version] or a folder (default: this checkout when run inside one, else @latest)
  -o <file>         the program to write (default news-server, news-server.exe on Windows)
  --keep            keep the build folder, and print where it is
`

// module is a Go module to build with: fetched at Version, or taken from the folder Dir.
type module struct {
	Path    string
	Version string
	Dir     string
}

type withFlag []string

func (w *withFlag) String() string     { return strings.Join(*w, ",") }
func (w *withFlag) Set(v string) error { *w = append(*w, v); return nil }

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "newsbuild:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	flags := flag.NewFlagSet("newsbuild", flag.ContinueOnError)
	flags.Usage = func() { fmt.Fprint(os.Stderr, usage) }
	var with withFlag
	flags.Var(&with, "with", "")
	core := flags.String("core", "", "")
	out := flags.String("o", "", "")
	keep := flags.Bool("keep", false, "")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() > 0 {
		return fmt.Errorf("unexpected %q\n%s", flags.Arg(0), usage)
	}

	coreMod, err := coreModuleFor(*core)
	if err != nil {
		return err
	}
	var packs []module
	for _, w := range with {
		m, err := parseModule(w)
		if err != nil {
			return err
		}
		packs = append(packs, m)
	}

	output := *out
	if output == "" {
		output = "news-server"
		if goos() == "windows" {
			output += ".exe"
		}
	}
	if output, err = filepath.Abs(output); err != nil {
		return err
	}

	dir, err := os.MkdirTemp("", "newsbuild-")
	if err != nil {
		return err
	}
	if *keep {
		fmt.Println("build folder:", dir)
	} else {
		defer os.RemoveAll(dir)
	}

	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(mainSource(packs)), 0o644); err != nil {
		return err
	}
	if err := goCmd(dir, "mod", "init", "newsbuild.local/news-server"); err != nil {
		return err
	}
	all := append([]module{coreMod}, packs...)
	for _, m := range all {
		if m.Dir != "" {
			if err := goCmd(dir, "mod", "edit", "-replace", m.Path+"="+m.Dir, "-require", m.Path+"@"+pseudo); err != nil {
				return err
			}
		}
	}
	for _, m := range all {
		if m.Dir == "" {
			if err := goCmd(dir, "get", m.Path+"@"+m.Version); err != nil {
				return err
			}
		}
	}
	if err := goCmd(dir, "mod", "tidy"); err != nil {
		return err
	}
	version := "newsbuild " + time.Now().Format("2006-01-02")
	if err := goCmd(dir, "build", "-o", output, "-ldflags", "-X '"+coreModule+".version="+version+"'", "."); err != nil {
		return err
	}
	fmt.Println("built", output)
	return nil
}

// mainSource is the main package: the core's Main, after every pack's init.
func mainSource(packs []module) string {
	var b strings.Builder
	b.WriteString("// Code generated by newsbuild. DO NOT EDIT.\n\npackage main\n\nimport (\n")
	b.WriteString("\tnewsserver \"" + coreModule + "\"\n")
	for _, p := range packs {
		b.WriteString("\t_ \"" + p.Path + "\"\n")
	}
	b.WriteString(")\n\nfunc main() { newsserver.Main() }\n")
	return b.String()
}

// coreModuleFor is the core named by --core; when it is empty, the checkout newsbuild runs in, else @latest.
func coreModuleFor(spec string) (module, error) {
	if spec != "" {
		m, err := parseModule(spec)
		if err == nil && m.Path != coreModule {
			err = fmt.Errorf("--core %s is the module %s, not %s", spec, m.Path, coreModule)
		}
		return m, err
	}
	if dir, err := os.Getwd(); err == nil {
		for {
			if path, err := modulePath(dir); err == nil && path == coreModule {
				return module{Path: coreModule, Dir: dir}, nil
			}
			parent := filepath.Dir(dir)
			if parent == dir {
				break
			}
			dir = parent
		}
	}
	return module{Path: coreModule, Version: "latest"}, nil
}

// parseModule reads a --with or --core value: a folder holding a go.mod, or module[@version].
func parseModule(spec string) (module, error) {
	if isFolder(spec) {
		dir, err := filepath.Abs(spec)
		if err != nil {
			return module{}, err
		}
		path, err := modulePath(dir)
		if err != nil {
			return module{}, fmt.Errorf("%s: %w", spec, err)
		}
		return module{Path: path, Dir: dir}, nil
	}
	path, version, found := strings.Cut(spec, "@")
	if !found || version == "" {
		version = "latest"
	}
	if path == "" {
		return module{}, fmt.Errorf("no module in %q", spec)
	}
	return module{Path: path, Version: version}, nil
}

func isFolder(spec string) bool {
	if strings.HasPrefix(spec, ".") || filepath.IsAbs(spec) || (len(spec) > 1 && spec[1] == ':') {
		return true
	}
	info, err := os.Stat(spec)
	return err == nil && info.IsDir()
}

// modulePath is the module line of dir/go.mod.
func modulePath(dir string) (string, error) {
	f, err := os.Open(filepath.Join(dir, "go.mod"))
	if err != nil {
		return "", err
	}
	defer f.Close()
	lines := bufio.NewScanner(f)
	for lines.Scan() {
		line := strings.TrimSpace(lines.Text())
		if rest, ok := strings.CutPrefix(line, "module "); ok {
			return strings.Trim(strings.TrimSpace(rest), `"`), nil
		}
	}
	return "", errors.New("go.mod has no module line")
}

// goCmd runs the go command in dir, showing its output.
func goCmd(dir string, args ...string) error {
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("go %s: %w", strings.Join(args, " "), err)
	}
	return nil
}

func goos() string {
	if v := os.Getenv("GOOS"); v != "" {
		return v
	}
	return runtime.GOOS
}
